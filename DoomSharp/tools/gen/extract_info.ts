// Generates DoomSharp/src/DoomSharp.Core/InfoTables.g.cs from the C
// characterization dump (tools/charact/info_vectors.json) produced by
// infodump.c over the UNMODIFIED linuxdoom-1.10 info.c.
//
// Run from repo root:  node DoomSharp/tools/gen/extract_info.ts
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../../", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const vectors = JSON.parse(readFileSync(root + "DoomSharp/tools/charact/info_vectors.json", "utf8"));

const states = vectors.states as StateRow[];
const mobjinfo = vectors.mobjinfo as MobjRow[];
const sprnames = vectors.sprnames as string[];

interface StateRow {
  sprite: number; frame: number; tics: number; action: string | null; next: number;
}
interface MobjRow {
  doomednum: number; spawnstate: number; spawnhealth: number;
  seestate: number; seesound: number; reactiontime: number;
  attacksound: number; painstate: number; painchance: number;
  painsound: number; meleestate: number; missilestate: number;
  deathstate: number; xdeathstate: number; deathsound: number;
  speed: number; radius: number; height: number; mass: number;
  damage: number; activesound: number; flags: number; raisestate: number;
}

// Collect distinct action names -> enum members.
const actionNames = [...new Set(states.map(s => s.action).filter(a => a !== "null"))].sort();
const actionEnum = actionNames.map(a => `    ${a} = ${actionNames.indexOf(a) + 1},`).join("\n");

const lines: string[] = [];
lines.push(`// <auto-generated />`);
lines.push(`// Generated by DoomSharp/tools/gen/extract_info.ts from the C characterization`);
lines.push(`// dump (tools/charact/info_vectors.json) over the UNMODIFIED linuxdoom-1.10`);
lines.push(`// info.c. Do not edit by hand; regenerate instead.`);
lines.push(``);
lines.push(`using DoomSharp.Core;`);
lines.push(``);
lines.push(`namespace DoomSharp.Core;`);
lines.push(``);
lines.push(`/// <summary>NUMSPRITES (info.h).</summary>`);
lines.push(`public static partial class InfoTables`);
lines.push(`{`);
lines.push(`    public const int NumSprites = ${vectors.numSprites};`);
lines.push(`    public const int NumStates = ${vectors.numStates};`);
lines.push(`    public const int NumMobjTypes = ${vectors.numMobjTypes};`);
lines.push(``);
lines.push(`    /// <summary>sprnames[] (info.c) — canonical sprite lump base names.</summary>`);
lines.push(`    public static readonly string[] SpriteNames =`);
lines.push(`    [`);
lines.push(...sprnames.map(n => `        "${n}",`));
lines.push(`    ];`);
lines.push(``);
lines.push(`    /// <summary>states[] — sprite, frame, tics, action, nextstate.</summary>`);
lines.push(`    public static readonly StateDef[] States =`);
lines.push(`    [`);
for (const s of states) {
  lines.push(`        new(${s.sprite}, ${s.frame}, ${s.tics}, StateAction.${s.action === "null" ? "None" : s.action}, ${s.next}),`);
}
lines.push(`    ];`);
lines.push(``);
lines.push(`    /// <summary>mobjinfo[] — one row per mobjtype_t.</summary>`);
lines.push(`    public static readonly MobjInfo[] MobjInfo =`);
lines.push(`    [`);
for (const m of mobjinfo) {
  lines.push(`        new(${m.doomednum}, ${m.spawnstate}, ${m.spawnhealth}, ${m.seestate}, ${m.seesound}, ${m.reactiontime}, ${m.attacksound}, ${m.painstate}, ${m.painchance}, ${m.painsound}, ${m.meleestate}, ${m.missilestate}, ${m.deathstate}, ${m.xdeathstate}, ${m.deathsound}, ${m.speed}, ${m.radius}, ${m.height}, ${m.mass}, ${m.damage}, ${m.activesound}, ${m.flags}, ${m.raisestate}),`);
}
lines.push(`    ];`);
lines.push(`}`);
lines.push(``);
lines.push(`/// <summary>state_t.action — enum of action function names (dispatch in DOOM-021b).</summary>`);
lines.push(`public enum StateAction`);
lines.push(`{`);
lines.push(`    None = 0,`);
lines.push(actionEnum);
lines.push(`}`);
lines.push(``);
lines.push(`/// <summary>state_t (info.h:1147-1160).</summary>`);
lines.push(`public readonly record struct StateDef(int Sprite, int Frame, int Tics, StateAction Action, int NextState);`);
lines.push(``);
lines.push(`/// <summary>mobjinfo_t (info.h:1305-1340).</summary>`);
lines.push(`public readonly record struct MobjInfo(`);
lines.push(`    int DoomedNum,`);
lines.push(`    int SpawnState,`);
lines.push(`    int SpawnHealth,`);
lines.push(`    int SeeState,`);
lines.push(`    int SeeSound,`);
lines.push(`    int ReactionTime,`);
lines.push(`    int AttackSound,`);
lines.push(`    int PainState,`);
lines.push(`    int PainChance,`);
lines.push(`    int PainSound,`);
lines.push(`    int MeleeState,`);
lines.push(`    int MissileState,`);
lines.push(`    int DeathState,`);
lines.push(`    int XDeathState,`);
lines.push(`    int DeathSound,`);
lines.push(`    int Speed,`);
lines.push(`    int Radius,`);
lines.push(`    int Height,`);
lines.push(`    int Mass,`);
lines.push(`    int Damage,`);
lines.push(`    int ActiveSound,`);
lines.push(`    uint Flags,`);
lines.push(`    int RaiseState);`);
lines.push(``);

writeFileSync(root + "DoomSharp/src/DoomSharp.Core/InfoTables.g.cs", lines.join("\n"));
console.log(`InfoTables.g.cs: ${sprnames.length} sprites, ${states.length} states, ${mobjinfo.length} mobj types, ${actionNames.length} actions`);
